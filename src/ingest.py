
"""
RPKI-PathWatch: first real-data ingestion probe.

Fetches:
  1. BGP state observed by RIPE RIS at a requested timestamp.
  2. The current RPKI validation result for a prefix-origin pair.

IMPORTANT:
The RPKI validation endpoint used here is a current lookup.
It must not be treated as the RPKI state at the historical BGP timestamp.
No synthetic observations are generated by this script.
"""

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlencode

import requests


ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "raw"

BASE_URL = "https://stat.ripe.net/data"
TIMEOUT_SECONDS = 30


def get_json(endpoint: str, params: dict) -> dict:
    """Fetch a JSON response and fail clearly on HTTP/API errors."""
    url = f"{BASE_URL}/{endpoint}/data.json"

    response = requests.get(
        url,
        params=params,
        timeout=TIMEOUT_SECONDS,
        headers={"User-Agent": "RPKI-PathWatch/0.1"},
    )
    response.raise_for_status()

    payload = response.json()

    if payload.get("status") == "error":
        raise RuntimeError(
            f"RIPE Stat API error from {endpoint}: "
            f"{payload.get('messages', payload)}"
        )

    return payload


def parse_timestamp(value: str) -> str:
    """Validate timestamp and normalize it to UTC ISO-8601."""
    parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))

    if parsed.tzinfo is None:
        raise ValueError(
            "Timestamp must include a timezone, e.g. "
            "2024-12-21T12:00:00Z"
        )

    return parsed.astimezone(timezone.utc).isoformat().replace("+00:00", "Z")


def save_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )


def run(prefix: str, origin_as: int, timestamp: str) -> None:
    RAW_DIR.mkdir(parents=True, exist_ok=True)

    # Historical BGP state, derived from a preceding RIB and updates.
    bgp_params = {
        "resource": prefix,
        "timestamp": timestamp,
    }

    print("[1/2] Fetching historical BGP state...")
    bgp = get_json("bgp-state", bgp_params)

    # Current RPKI validation lookup. This is NOT historical validation.
    rpki_params = {
        "resource": origin_as,
        "prefix": prefix,
    }

    print("[2/2] Fetching current RPKI validation snapshot...")
    rpki = get_json("rpki-validation", rpki_params)

    run_id = (
        timestamp.replace(":", "")
        .replace("-", "")
        .replace("T", "_")
        .replace("Z", "")
    )
    prefix_tag = prefix.replace("/", "_")

    bgp_path = RAW_DIR / f"bgp_{prefix_tag}_{run_id}.json"
    rpki_path = RAW_DIR / f"rpki_current_{prefix_tag}_{origin_as}.json"
    manifest_path = RAW_DIR / f"manifest_{prefix_tag}_{run_id}.json"

    save_json(bgp_path, bgp)
    save_json(rpki_path, rpki)

    manifest = {
        "project": "RPKI-PathWatch",
        "run_timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "prefix": prefix,
        "origin_as": origin_as,
        "sources": {
            "bgp_state": {
                "endpoint": f"{BASE_URL}/bgp-state/data.json",
                "query": bgp_params,
                "observation_time": timestamp,
                "historical": True,
                "file": str(bgp_path.relative_to(ROOT)),
            },
            "rpki_validation": {
                "endpoint": f"{BASE_URL}/rpki-validation/data.json",
                "query": rpki_params,
                "observation_time": "query time; current lookup",
                "historical": False,
                "file": str(rpki_path.relative_to(ROOT)),
            },
        },
        "warning": (
            "The current RPKI validation result is not evidence of the "
            "validation state at the historical BGP timestamp. Do not "
            "correlate these as a historical transition."
        ),
        "synthetic_data_used": False,
    }

    save_json(manifest_path, manifest)

    bgp_data = bgp.get("data", {})
    rpki_data = rpki.get("data", {})

    print("\nIngestion completed.")
    print(f"Prefix:              {prefix}")
    print(f"Origin AS requested:  AS{origin_as}")
    print(f"BGP query time:       {timestamp}")
    print(f"Current RPKI status:  {rpki_data.get('status', 'inspect raw JSON')}")
    print("\nFiles saved:")
    print(f"  {bgp_path.relative_to(ROOT)}")
    print(f"  {rpki_path.relative_to(ROOT)}")
    print(f"  {manifest_path.relative_to(ROOT)}")
    print("\nImportant: inspect the raw BGP response to verify the")
    print("observed origins and paths. A prefix query can return")
    print("multiple routes; it does not guarantee AS{origin_as} is present.")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Fetch real RIPE Stat BGP and RPKI data."
    )
    parser.add_argument(
        "--prefix",
        default="193.0.0.0/21",
        help="IP prefix to query (default: documented RIPE example)",
    )
    parser.add_argument(
        "--origin-as",
        type=int,
        default=3333,
        help="Origin ASN for the RPKI lookup (default: documented example)",
    )
    parser.add_argument(
        "--timestamp",
        default="2024-12-21T12:00:00Z",
        help="Historical BGP query timestamp with timezone",
    )

    args = parser.parse_args()

    try:
        timestamp = parse_timestamp(args.timestamp)
        run(args.prefix, args.origin_as, timestamp)
    except (requests.RequestException, ValueError, RuntimeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
